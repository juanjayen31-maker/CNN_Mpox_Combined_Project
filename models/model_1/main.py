"""Membuat Fungsi Arsitektur CNN"""

# Membuat arsitektur Simple CNN

class SimpleCNN(nn.Module):

    def __init__(self, num_classes=6):
        super(SimpleCNN, self).__init__()

        # Feature Extraction
        self.features = nn.Sequential(

            nn.Conv2d(3, 20, kernel_size=(5, 5)),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=(3, 3)),

            nn.Conv2d(20, 50, kernel_size=(5, 5)),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=(3, 3))
        )

        # Classification
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(50 * 9 * 9, num_classes)
        )

    def forward(self, x):
        x = self.features(x)
        x = self.classifier(x)
        return x


print("Arsitektur Simple CNN berhasil dibuat!")

"""Pengaturan Hyperparameter"""

# Pengaturan hyperparameter

num_epochs = 10
batch_size = 32
learning_rate = 0.001

# Folder untuk menyimpan hasil evaluasi
results_path = "Hasil_5_Fold"

os.makedirs(results_path, exist_ok=True)

